-- Accounting schema reference
-- IMPORTANT:
--   The authoritative production DDL is the cumulative result of files under
--   supabase/migrations/. This file is a compact reference, not a migration to
--   apply directly.
--
-- Key production rules as of 2026-10-12:
--
-- 1) accounting schema is private; RLS enabled; anon/authenticated access revoked.
--
-- 2) Core tables:
--    companies, fiscal_years, accounts, sub_accounts,
--    journals, journal_lines, receipts, journal_receipts,
--    import_files, bank_transactions, card_transactions, audit_logs.
--
-- 3) Reconciliation tables:
--    reconciliation_groups
--    reconciliation_group_card_transactions
--    reconciliation_group_journals
--
-- 4) Reporting / reconciliation views:
--    general_ledger_v
--    trial_balance_v
--    monthly_profit_loss_v
--    monthly_balance_sheet_v
--    annual_profit_loss_v
--    annual_balance_sheet_v
--    card_transaction_reconciliation_v
--    bank_transaction_reconciliation_v
--
-- 5) Journal construction:
--    Draft journals may be temporarily unbalanced while lines are being built.
--    The old always-on journals_totals_check has been removed.
--    validate_journal_posting enforces, on draft -> posted:
--      - at least 2 lines
--      - debit > 0
--      - debit = credit
--
-- 6) Finalized journals:
--    posted / reversed journals and their lines are immutable.
--    Corrections are represented by reversal / adjustment journals.
--
-- 7) Evidence:
--    receipts supports CloudBox/source metadata and may contain NULL in fields
--    that could not be verified during historical import.
--    Evidence originals are append-only in principle.
--
-- 8) Import deduplication:
--    import_files: unique company/source_system/sha256
--    bank_transactions: unique company/source_system/source_row_hash
--    card_transactions: unique company/source_system/source_row_hash
--
-- 9) Card reconciliation:
--    Direct one-to-one matches use matched_journal_id.
--    Ambiguous but collectively proven many-to-many cases use
--    reconciliation_groups and association tables.
--
-- 10) Bank reconciliation:
--     bank_transactions.reconciliation_status:
--       direct
--       pending_journal
--       review
--       unmatched
--     matched_journal_id implies direct.
--
-- 11) Private Storage buckets:
--     accounting-receipts
--     accounting-imports
--
-- To inspect or change the real schema, use the migration files, not this file.
